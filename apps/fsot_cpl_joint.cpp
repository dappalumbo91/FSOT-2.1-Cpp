// fsot_cpl_joint: joint CPL (w0, w_a) chi^2 report (SPEC t1027s4342 §2, Damian t1027s4342; Scout bank 43_5ww).
// REPORTING ONLY: the kill band k is on HOLD (Damian t1031u, 2026-11-18 12:20 EST); no pass/fail verdict is printed.
// Engine values: wave4|w0 and validation_suite|Dark_energy_wa (canonical w_a, docs/addenda/CANONICAL_2026-11-18.md).
// Per combination: signed 1D pulls (facing-side sigma), chi^2 with facing-side sigmas and with symmetrized sigmas,
// and the 2-dof Gaussian-equivalent significance n_sigma = sqrt(2) erfc^-1(p), p = exp(-chi^2/2).
// All four DESI DR2 combinations are reported; none is picked. Unite has no printed covariance: its 1D pulls are the
// report and its chi^2 (FoM-derived rho ~ -0.91) is a labelled approximate sensitivity line.
#include <cmath>
#include <cstdlib>
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

#include "fsot/engine.hpp"
#include "fsot/host/sigma_fsot.hpp"

using namespace fsot;
using R = mp169;

static double to_d(const R& x) { return std::strtod(x.str(17, std::ios_base::scientific).c_str(), nullptr); }

static double nsig_2dof(double chi2) {  // p = exp(-chi2/2); invert two-sided Gaussian tail by bisection on erfc
  const double p = std::exp(-0.5 * chi2);
  double lo = 0, hi = 40;
  for (int i = 0; i < 200; ++i) { const double m = 0.5 * (lo + hi); (std::erfc(m / std::sqrt(2.0)) > p ? lo : hi) = m; }
  return 0.5 * (lo + hi);
}

int main(int argc, char** argv) {
  std::string ref_p, out_p;
  for (int i = 1; i + 1 < argc; i += 2) {
    const std::string a = argv[i];
    if (a == "--refs") ref_p = argv[i + 1];
    else if (a == "--out") out_p = argv[i + 1];
  }
  if (ref_p.empty()) { std::fprintf(stderr, "usage: fsot_cpl_joint --refs cpl.tsv [--out report.tsv]\n"); return 2; }
  Engine<R> eng;
  double w0 = 0, wa = 0; int found = 0;
  for (auto& [name, fn] : eng.sections())
    for (auto& r : (eng.*fn)()) {
      const std::string key = std::string(name) + "|" + r.name;
      if (key == "wave4|w0") { w0 = to_d(R(r.computed)); ++found; }
      if (key == "validation_suite|Dark_energy_wa") { wa = to_d(R(r.computed)); ++found; }
    }
  if (found != 2) { std::fprintf(stderr, "engine rows wave4|w0 / validation_suite|Dark_energy_wa not found (%d)\n", found); return 2; }
  FILE* out = out_p.empty() ? stdout : std::fopen(out_p.c_str(), "wb");
  std::fprintf(out, "# generated by apps/fsot_cpl_joint.cpp; REPORTING ONLY (k on HOLD, Damian t1031u); no verdict\n");
  std::fprintf(out, "# engine w0=%.12g (wave4|w0)  w_a=%.12g (validation_suite|Dark_energy_wa, canonical addendum 2026-11-18)\n", w0, wa);
  std::fprintf(out, "#id\trho\trho_status\tz_w0\tz_wa\tchi2_facing\tnsigma_2dof_facing\tchi2_symmetrized\tnsigma_2dof_symmetrized\tlabel\n");
  std::ifstream f(ref_p);
  std::string line;
  while (std::getline(f, line)) {
    if (line.empty() || line[0] == '#') continue;
    std::vector<std::string> c; std::stringstream ss(line); std::string t;
    while (std::getline(ss, t, '\t')) c.push_back(t);
    if (c.size() < 10) { std::fprintf(stderr, "bad row: %s\n", line.c_str()); return 2; }
    const double c0 = std::stod(c[1]), s0m = std::stod(c[2]), s0p = std::stod(c[3]);
    const double ca = std::stod(c[4]), sam = std::stod(c[5]), sap = std::stod(c[6]), rho = std::stod(c[7]);
    const double d0 = w0 - c0, da = wa - ca;
    const double s0f = d0 >= 0 ? s0p : s0m, saf = da >= 0 ? sap : sam;
    const double s0s = 0.5 * (s0m + s0p), sas = 0.5 * (sam + sap);
    const double chf = sigma::chi2_2d(d0, da, s0f, saf, rho), chs = sigma::chi2_2d(d0, da, s0s, sas, rho);
    const std::string label = c[8] == "CHAIN" ? "rho Scout-derived from official chains"
                            : c[8] == "FOM_APPROX" ? "1D pulls are the report; chi2 is an APPROXIMATE sensitivity line (FoM-derived rho, not printed)"
                                                   : c[8];
    std::fprintf(out, "%s\t%+.3f\t%s\t%+.4f\t%+.4f\t%.4f\t%.3f\t%.4f\t%.3f\t%s\n", c[0].c_str(), rho, c[8].c_str(), d0 / s0f, da / saf,
                 chf, nsig_2dof(chf), chs, nsig_2dof(chs), label.c_str());
  }
  if (out != stdout) std::fclose(out);
  return 0;
}
