    emit(S, "G_F GeV^-2", tag, G, *ref("G_F_GeVm2"), "frozen-pending")
    info(S, "Gamma_Z^fit GeV (Freitas, G_mu internal)", "", GZfit); info(S, "s2 mapping delta", "s2_OS(leaf) - s2_OS(M_W^fit)", dS2)
    note = ("confirms only if V1, V2 pass and z<=1" + ("" if VALID else " -- VALIDATION FAILED: not confirmable")) if H == "H1" else "never confirmed (external)"
    emit(S, "Gamma_Z/M_Z", "GZ-1", GZ / MZ, *ref("Gamma_Z_over_M_Z"), note)
