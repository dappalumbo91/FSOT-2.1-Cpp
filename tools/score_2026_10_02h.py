ap = argparse.ArgumentParser(); ap.add_argument("--hub", required=True); ap.add_argument("--out", required=True)
ap.add_argument("--validate-only", action="store_true"); a = ap.parse_args()
rows = []
def emit(sec, name, inputs, v, c, s, note=""):
    zz = fabs(v - c) / s
    rows.append([sec, name, inputs, nstr(v, 15), nstr(c, 12), nstr(s, 5), nstr(zz, 5), "PASS" if zz <= 1 else "FAIL", nstr((v - c) / c * 10**6, 6), note])
def info(sec, name, inputs, v, note=""):
    rows.append([sec, name, inputs, nstr(v, 15), "-", "-", "-", "info", "-", note])
def write():
    with open(a.out, "w") as o:
        o.write("# generated by tools/score_2026_10_02h.py under audit/FREEZE_2026-10-02h (committed first)\n#section\tname\tinputs\tvalue\tcentral\tsigma\tz\tz<=1\tppm\tnote\n")
        for r in rows: o.write("\t".join(str(x) for x in r) + "\n")
ref = X.refs(); z3 = zeta(3)

# ---- GZ-1 building blocks (hep-ph/0311148; arXiv:1401.2447)
def mw_acfw(MH, mt, MZ, dal, als):  # eqs. fitformula, pardef, fitparams
    dH = ln(MH / 100); dh = (MH / 100) ** 2; dt = (mt / mpf("174.3")) ** 2 - 1; dZ = MZ / mpf("91.1875") - 1
    da = dal / mpf("0.05907") - 1; das = als / mpf("0.119") - 1
    return (mpf("80.3779") - mpf("0.05427") * dH - mpf("0.008931") * dH**2 + mpf("0.0000882") * dH**4 + mpf("0.000161") * (dh - 1)
            - mpf("1.070") * da + mpf("0.5237") * dt - mpf("0.0679") * dt**2 - mpf("0.00179") * dH * dt + mpf("0.0000664") * dh * dt
            - mpf("0.0795") * das + mpf("114.9") * dZ)
GZC = [mpf(x) for x in "2494.24 -3.725 -2.019 1.773 -0.04554 19.63 -2.0 -0.36 0.257 58.60 -4.1 -0.53 7.6 -56.0 1.3 9256".split()]
def gz_freitas(MH, mt, MZ, dal, als):  # eq. par2, tab:fit2 row Gamma_Z, MeV -> GeV
    LH = ln(MH / mpf("125.7")); DH = MH / mpf("125.7") - 1; Dt = (mt / mpf("173.2")) ** 2 - 1; Das = als / mpf("0.1184") - 1
    Da = dal / mpf("0.059") - 1; DZ = MZ / mpf("91.1876") - 1; c = GZC
    return (c[0] + c[1] * LH + c[2] * LH**2 + c[3] * DH + c[4] * DH**2 + c[5] * Dt + c[6] * Dt**2 + c[7] * Dt * LH + c[8] * Dt * LH**2
            + c[9] * Das + c[10] * Das**2 + c[11] * Das * LH + c[12] * Das * Dt + c[13] * Da + c[14] * Da * LH + c[15] * DZ) / 1000
def gamma_w(G, MW, als): return 3 * G * MW**3 / (2 * sqrt(2) * pi) * (1 + 2 * als / (3 * pi))
def pole(M, G): return M / sqrt(1 + (G / M) ** 2)
G_ACFW, AL_ACFW, GZ_ACFW, G_FR = mpf("1.166379e-5"), 1 / mpf("137.03599976"), mpf("2.4952"), mpf("1.16638e-5")
def delta_r(MH, mt, MZ, dal, als):
    MW = mw_acfw(MH, mt, MZ, dal, als); mwb, mzb = pole(MW, gamma_w(G_ACFW, MW, als)), pole(MZ, GZ_ACFW)
    return sqrt(2) * G_ACFW * mwb**2 * (1 - mwb**2 / mzb**2) / (pi * AL_ACFW) - 1, MW
def gf_from(al, MW, MZ, dr, als, GZ):
    G = mpf("1.1663787e-5")
    for _ in range(60):
        mwb, mzb = pole(MW, gamma_w(G, MW, als)), pole(MZ, GZ)
        new = pi * al * (1 + dr) / (sqrt(2) * mwb**2 * (1 - mwb**2 / mzb**2))
        if fabs(new - G) / G < mpf(10) ** -25: return new
        G = new
    return G
def d_s(s2, als):
    fs = [(-1, -mpf(1) / 2, 1, 3), (0, mpf(1) / 2, 1, 3), (mpf(2) / 3, mpf(1) / 2, 3 * (1 + als / pi), 2), (-mpf(1) / 3, -mpf(1) / 2, 3 * (1 + als / pi), 3)]
    num = sum(n * w * 2 * (T - 2 * Q * s2) * (-2 * Q) for Q, T, w, n in fs); den = sum(n * w * ((T - 2 * Q * s2) ** 2 + T**2) for Q, T, w, n in fs)
    return num / den
def dalep(al, MZ, masses):
    return (al / (3 * pi) * sum(ln(MZ**2 / m**2) - mpf(5) / 3 for m in masses)
            + (al / pi) ** 2 * sum(ln(MZ**2 / m**2) / 4 + z3 - mpf(5) / 24 for m in masses))

