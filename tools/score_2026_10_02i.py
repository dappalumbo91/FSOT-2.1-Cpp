# ---- HAD-1: De Rujula-Georgi-Glashow constituent quark model (PRD 12, 147 (1975)), A_B = A_M/2
def dgg_mrho(mpi, mN):
    # pi: 2m - 0.75 x ; N: 3m - 0.375 x  (x = A/m^2)  ->  m_rho = 2m + 0.25 x
    m = (2 * mN - mpi) / 4; x = (2 * m - mpi) / mpf("0.75")
    return 2 * m + x / 4, m, x

# ---- HAD-2: quark-hadron duality R-ratio (pure-float, deterministic; printed to 10 significant digits)
Z3 = 1.2020569031595942
def beta(a, nf):  # d alpha / d ln mu^2, 4-loop MSbar (PDG 2024 QCD review eq. 9.4)
    b0 = (33 - 2 * nf) / (12 * math.pi); b1 = (153 - 19 * nf) / (24 * math.pi**2)
    b2 = (2857 - 5033 / 9 * nf + 325 / 27 * nf**2) / (128 * math.pi**3)
