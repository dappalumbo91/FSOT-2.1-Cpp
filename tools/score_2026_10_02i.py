def mw_acfw(MH, mt, MZ, dal, als):  # eqs. fitformula, pardef, fitparams
    dH = ln(MH / 100); dh = (MH / 100) ** 2; dt = (mt / mpf("174.3")) ** 2 - 1; dZ = MZ / mpf("91.1875") - 1
