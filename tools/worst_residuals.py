#!/usr/bin/env python3
"""Rank the worst remaining out-of-bar observables of the single engine (what to dial in next).

Inputs (all written by the C++ build): <build>/precision_2026-10-02.tsv (fsot_precision: z vs published sigma),
<build>/single_engine_table.tsv and <build>/single_engine_folded.tsv (fsot_single_engine), and
golden/ledger_b_genuine_misses_6f9c2560.tsv. Bar: |z| > 1 against the published uncertainty (owner standing rule)
for scored rows; rel > 0.5 % for rows that carry no sigma (the archive's certificate bar). (l): rows whose target is
V_ud or g_A are listed separately and never ranked. Rows flagged SM_PARITY_REFINE_LATER (§43.5vt G_F and every row
that reads it; Damian t994u) are listed in section D with their gates and are not ranked in A; ALTERNATE rows are skipped. Usage: worst_residuals.py <build_dir> <out.md>"""
import csv, sys
from pathlib import Path
B, OUT = Path(sys.argv[1]), Path(sys.argv[2])
SRC = Path(__file__).resolve().parent.parent
EXCL = ("V_ud", "g_A")
def excluded(s): return any(x in s for x in EXCL)
def tsv(p):
    rows = list(csv.reader(open(p), delimiter="\t"))
    h = [c.lstrip("#") for c in rows[0]]
    return [dict(zip(h, r)) for r in rows[1:] if r and not r[0].startswith("#")]
scored, unscored, excl, smp = [], [], [], []
for r in tsv(B / "precision_2026-10-02.tsv"):
    try: z = float(r["z"])
    except ValueError: continue
    item = dict(obs=r["id"], src="fsot_precision (record=%s, %s)" % (r["record"], r["route"]), value=r["value"], ref=f'{r["central"]} ± {r["sigma_plus"]}', z=z, note=r.get("source", "")[:60])
    (excl if excluded(r["id"]) else scored).append(item)
for r in tsv(B / "single_engine_folded.tsv"):
    if not r["z_live"]: continue
    flag = r.get("flag", "")
    if "ALTERNATE" in flag: continue
    if "SM_PARITY_REFINE_LATER" in flag:
        smp.append(dict(obs=f'{r["route"]} [{r["leaf"]}]', value=f'{float(r["pred_live"]):.12g}', ref=f'{r["obs"]} ± {r["sigma"]}', z=float(r["z_live"]), flag=flag)); continue
    item = dict(obs=f'{r["route"]} [{r["leaf"]}]', src="folded route (live: %s)" % (r["live"] or "recorded pred"), value=f'{float(r["pred_live"]):.12g}', ref=f'{r["obs"]} ± {r["sigma"]}', z=float(r["z_live"]), note="")
    if "GAQ2" in r["route"]: item["src"] += "; F_A(0) = -g_A input, g_A itself not scored ((l))"
    (excl if excluded(r["route"] + r["leaf"]) else scored).append(item)
tab = tsv(B / "single_engine_table.tsv")
for r in tab:
    if r["kind"] == "definition" or not r["rel_pct"]: continue
    if r["section"] == "validation_suite" and r["name"].startswith("V2"): continue  # relays of wave1 rows
    if r["z"]:
        scored.append(dict(obs=f'{r["section"]}|{r["name"]}', src="closed form (sigma in authority)", value=f'{float(r["value"]):.12g}', ref=f'{float(r["measured"]):.12g} ± {r["sigma"]}', z=float(r["z"]), note=r["sensitive"]))
    rel = float(r["rel_pct"])
    if rel > 0.5:
        unscored.append(dict(obs=f'{r["section"]}|{r["name"]}', formula=r["formula"], value=f'{float(r["value"]):.12g}', ref=f'{float(r["measured"]):.12g}', rel=rel, sens=r["sensitive"].strip(),
                             alt=(f'10phi {abs(float(r["value_c_cosm_10phi"]) - float(r["measured"])) / abs(float(r["measured"])) * 100:.4f}%' if "D-02" in r["sensitive"] else "") +
                                 (f' QM-D5 {abs(float(r["value_qm_D5"]) - float(r["measured"])) / abs(float(r["measured"])) * 100:.4f}%' if "D-04" in r["sensitive"] else "")))
for r in tsv(SRC / "golden/ledger_b_genuine_misses_6f9c2560.tsv"):
    unscored.append(dict(obs=f'ledger B {r["file"]}:{r["name"]}', formula=r.get("property", ""), value=r["computed"], ref=r["measured"], rel=float(r["recomputed_error_pct"]), sens="", alt="within literature band" if r["within_literature"] == "True" else ""))
out_s = sorted([s for s in scored if abs(s["z"]) > 1], key=lambda s: -abs(s["z"]))
out_u = sorted(unscored, key=lambda s: -s["rel"])
L = ["# Worst remaining out-of-bar observables (generated by `tools/worst_residuals.py`; single engine = pin AEB2AD, C_cosm 1/(φπ²), QM rung 6)", "",
     f"Scored rows considered: {len(scored)} (|z| > 1 out of bar: {len(out_s)}). Unscored rows over 0.5 %: {len(out_u)}. (l) rows set aside: {len(excl)}.", "",
     "## A. Scored against the published uncertainty, |z| > 1 (dial-in priority)", "", "| rank | observable | source | engine value | reference | z |", "|---|---|---|---|---|---|"]
for i, s in enumerate(out_s, 1): L.append(f'| {i} | `{s["obs"]}` | {s["src"]} | {s["value"]} | {s["ref"]} | {s["z"]:+.3f} |')
L += ["", "## B. No published sigma in the engine row; rel > 0.5 % (needs a sigma, then a route)", "", "| rank | observable | formula | engine value | target | rel % | variant sensitivity | rel % under the alternative |", "|---|---|---|---|---|---|---|---|"]
for i, s in enumerate(out_u, 1): L.append(f'| {i} | `{s["obs"]}` | {s["formula"]} | {s["value"]} | {s["ref"]} | {s["rel"]:.4f} | {s["sens"]} | {s["alt"]} |')
L += ["", "## C. Set aside by (l) (never ranked)", ""] + [f'- `{s["obs"]}` z {s["z"]:+.3f}' for s in excl]
L += ["", "## D. Folded at SM parity, refine later (§43.5vt, Damian t994u; ruling t992u c65ff89d) — not ranked in A", "",
      "Carried route P2. Gate A = |z| ≤ 1; G_F is ACCEPTED at Gate B (|G_F − G_μ| ≤ 809.87 ppm). §43.5vv / vw / vx keep refining these.", "",
      "| row | engine value | reference | z | flag |", "|---|---|---|---|---|"]
L += [f'| `{s["obs"]}` | {s["value"]} | {s["ref"]} | {s["z"]:+.3f} | {s["flag"]} |' for s in sorted(smp, key=lambda s: -abs(s["z"]))] + [""]
OUT.write_text("\n".join(L))
print(f"scored {len(scored)} out-of-bar {len(out_s)}; unscored>0.5% {len(out_u)}; excluded {len(excl)}")
